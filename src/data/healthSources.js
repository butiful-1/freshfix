export function sourcesForTopics(topics = []) {
  const wanted = new Set(topics)
  const list = HEALTH_SOURCES.filter(s => s.topics.some(t => wanted.has(t)))
  // Keep registry order (most general first) but put exact-topic matches first.
  return list
}

export function sourceById(id) {
  return HEALTH_SOURCES.find(s => s.id === id) || null
}
